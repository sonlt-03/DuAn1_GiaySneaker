    private void btnXoaHDCTActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaHDCTActionPerformed
    int selectedRow = tblLichSuHoaDon.getSelectedRow();
    if (selectedRow < 0) {
        JOptionPane.showMessageDialog(this, "Vui lòng chọn hóa đơn để hoàn tác thanh toán!");
        return;
    }

    int idHoaDon = Integer.parseInt(tblLichSuHoaDon.getValueAt(selectedRow, 0).toString());
    int confirmation = JOptionPane.showConfirmDialog(this, "Bạn có chắc chắn muốn hoàn tác thanh toán hóa đơn này?", "Hoàn tác hóa đơn", JOptionPane.YES_NO_OPTION);

    if (confirmation == JOptionPane.YES_OPTION) {
        try {
            boolean isUpdated = rp.updateTrangThaiHoaDonLS(idHoaDon, false);
            if (isUpdated) {
                JOptionPane.showMessageDialog(this, "Hoàn tác thanh toán thành công!");
                this.fillLSHD(rp.getLSHD());
                v.fillTable(rp.getAll());
            } else {
                JOptionPane.showMessageDialog(this, "Lỗi khi hoàn tác thanh toán!");
            }
        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Lỗi cơ sở dữ liệu: " + e.getMessage());
        }
    }
    }//GEN-LAST:event_btnXoaHDCTActionPerformed

