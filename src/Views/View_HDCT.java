    public void fillLSHD(List<LichSuHoaDon> list) {
    mol = (DefaultTableModel) tblLichSuHoaDon.getModel();
    mol.setRowCount(0); 
    for (LichSuHoaDon hd : list) {
        mol.addRow(new Object[]{
            hd.getIdHoaDon(),
            hd.getMaHoaDon(),
            hd.getIdNhanVien(),
            hd.getIdKhachHang(),
            hd.getIdPhieuGiamGia(),
            hd.getIdPTTT(),
            hd.getNgayTao(),
            hd.getTongTien(),
            hd.getGhiChu(),
            hd.getTrangThai()? "Đã thanh toán" : "Chưa thanh toán" 
        });
    }
}
